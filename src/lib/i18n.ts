export type TranslationVariables = Record<string, string | number | boolean | null | undefined>;

export const dictionaries: Record<Locale, Record<MessageKey, string>> = {
  en,
  am
};

export function isLocale(value: string | null | undefined): value is Locale {
  return value === "en" || value === "am";
}

export function translate(locale: Locale, key: MessageKey, variables: TranslationVariables = {}): string {
  return dictionaries[locale][key].replace(/\{(\w+)\}/g, (placeholder, name: string) => {
    const value = variables[name];
    return value === undefined || value === null ? placeholder : String(value);
  });
}

export function createTranslator(locale: Locale) {
  return (key: MessageKey, variables?: TranslationVariables) => translate(locale, key, variables);
}
